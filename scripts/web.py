#!/usr/bin/env python3
"""scripts/web.py: the web app's build from TypeScript (#1323). The sources are
workbench/chat_static/src/*.ts; the browser loads the plain scripts built from them, committed
beside index.html (app.js, stats.js, settings.js, sw.js), so users need no Node or compiler.

  build             compile src/ (tsconfig.json, the pages; tsconfig.sw.json, the service worker)
                    with the pinned TypeScript and write each script with its "generated" header
  check             the same build into a temp directory, compared byte for byte with the committed
                    scripts, and every committed script in chat_static/ one the build makes (CI's)
  tests TYPES       type-check the browser tests (tests/tsconfig.json) against the Node types in
                    TYPES, a node_modules holding @types/node (Playwright stays untyped: the tests
                    load it at run time from $PLAYWRIGHT)

The compiler is scripts/install-tsc.sh's (TypeScript 7, native, hash-checked, cached per user):
this runs it first, so the first build downloads it. Strict, and nothing is emitted on an error.
Standard library only, Python 3.11.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STATIC = ROOT / "workbench" / "chat_static"
SRC = STATIC / "src"
PROJECTS = ("tsconfig.json", "tsconfig.sw.json")
HEADER = ("// Generated by scripts/web.py from workbench/chat_static/src/{src}: do not edit; "
          "run python3 scripts/web.py build (TypeScript {version}).\n")
HEADER_RE = re.compile(r"// Generated by scripts/web\.py from workbench/chat_static/src/[\w.]+\.ts: do not edit;")


class Refused(Exception):
    """A build or check said no; the message names what and the fix."""


def tsc_version() -> str:
    m = re.search(r"^version=(\S+)$", (ROOT / "scripts" / "install-tsc.sh").read_text(), re.M)
    if not m:
        raise Refused("scripts/install-tsc.sh pins no version=")
    return m.group(1)


def tsc() -> str:
    """The pinned compiler's path, installed (and checked) by scripts/install-tsc.sh."""
    r = subprocess.run(["bash", str(ROOT / "scripts" / "install-tsc.sh")], capture_output=True, text=True)
    if r.returncode:
        raise Refused(f"scripts/install-tsc.sh failed: {r.stderr.strip()}")
    return r.stdout.strip().splitlines()[-1]


def compile_into(out: Path) -> dict[str, bytes]:
    """{name.js: its bytes with the header}, the projects compiled into `out`."""
    exe, version = tsc(), tsc_version()
    for project in PROJECTS:
        r = subprocess.run([exe, "-p", str(SRC / project), "--outDir", str(out), "--pretty", "false"],
                           capture_output=True, text=True, cwd=ROOT)
        if r.returncode:
            raise Refused(f"tsc -p workbench/chat_static/src/{project}:\n{(r.stdout + r.stderr).strip()}")
    built = {}
    for f in sorted(out.glob("*.js")):
        src = f.with_suffix(".ts").name
        if not (SRC / src).is_file():
            raise Refused(f"tsc wrote {f.name}, which no src/*.ts names")
        built[f.name] = HEADER.format(src=src, version=version).encode() + f.read_bytes()
    return built


def build() -> list[str]:
    """Writes each built script whose bytes changed; returns their names."""
    with tempfile.TemporaryDirectory(prefix="wb-web-") as tmp:
        built = compile_into(Path(tmp))
    wrote = []
    for name, body in built.items():
        f = STATIC / name
        if not f.is_file() or f.read_bytes() != body:
            f.write_bytes(body)
            wrote.append(name)
    return wrote


def check() -> list[str]:
    """What differs between the commit and the build, one line each; empty when it is current."""
    with tempfile.TemporaryDirectory(prefix="wb-web-") as tmp:
        built = compile_into(Path(tmp))
    out = []
    for name, body in built.items():
        f = STATIC / name
        if not f.is_file():
            out.append(f"workbench/chat_static/{name}: missing (python3 scripts/web.py build)")
        elif f.read_bytes() != body:
            out.append(f"workbench/chat_static/{name}: not what src/{Path(name).with_suffix('.ts')} builds "
                       "(python3 scripts/web.py build, and commit it)")
    for f in sorted(STATIC.glob("*.js")):
        if f.name not in built:
            out.append(f"workbench/chat_static/{f.name}: no src/*.ts builds it (write it as TypeScript in src/)")
    return out


def check_tests(types: Path) -> None:
    """tests/tsconfig.json, with `types`' @types/node."""
    types = types.resolve()
    if not (types / "@types" / "node").is_dir():
        raise Refused(f"{types} holds no @types/node (npm install --prefix DIR @types/node)")
    with tempfile.TemporaryDirectory(prefix="wb-web-") as tmp:
        cfg = Path(tmp) / "tsconfig.json"
        cfg.write_text(json.dumps({"extends": str(ROOT / "tests" / "tsconfig.json"), "compilerOptions": {
            "typeRoots": [str(types / "@types")]}}))
        r = subprocess.run([tsc(), "-p", str(cfg), "--pretty", "false"], capture_output=True, text=True, cwd=ROOT)
    if r.returncode:
        raise Refused(f"tsc -p tests/tsconfig.json:\n{(r.stdout + r.stderr).strip()}")


def main(argv: list[str]) -> int:
    cmd = argv[0] if argv else ""
    try:
        if cmd == "build" and len(argv) == 1:
            wrote = build()
            print("web: wrote " + ", ".join(wrote) if wrote else "web: current")
        elif cmd == "check" and len(argv) == 1:
            bad = check()
            if bad:
                print("\n".join(bad), file=sys.stderr)
                return 1
            print("web: the committed scripts are what src/ builds")
        elif cmd == "tests" and len(argv) == 2:
            check_tests(Path(argv[1]))
            print("web: the browser tests type-check")
        else:
            print(__doc__.strip(), file=sys.stderr)
            return 64
    except Refused as e:
        print(f"web: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
