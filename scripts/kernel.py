TABLES_HEAD = ("-- Generated by scripts/kernel.py tables from workbench's Python (store, ask_mcp, chat, spend): "
               "do not edit; run python3 scripts/kernel.py build.\n")
# kernel/BOUNDARY.md's denied imports: `X*` any module starting X, `X.*` X and those under it
DENIED = ("Effect*", "Control.Monad.ST*", "Data.Array.ST*", "Data.Array.Partial", "Unsafe.*",
          "Partial.Unsafe", "Record.Unsafe", "Debug.*")
DENIED_TEXT = ("localeCompare",)  # locale-dependent: the two hosts' engines may differ
# What the bundle must never hold: an effect, a host, a clock, chance or a locale
BUNDLE_DENIED = ("import(", "require(", "process.", "globalThis", "Date.now", "new Date", "Math.random",
                 "console.", "setTimeout", "setInterval", "Intl.", "toLocale", "localeCompare", "eval(",
                 "new Function", "fetch(", "Bun.", "Deno.")
PRIM = {"Prim.String": "string", "Prim.Number": "number", "Prim.Boolean": "boolean"}


class Refused(Exception):
    """A check or a download said no; the message names what and the fix."""


class NotWire(Refused):
    """An export's type is not a wire type (kernel/BOUNDARY.md, *Wire types*)."""


# --- paths --------------------------------------------------------------------------------------

def paths(root: Path = ROOT) -> dict[str, Path]:
    k = root / "kernel"
    return {"kernel": k, "src": k / "src", "test": k / "test", "pin": k / "toolchain.json", "lock": k / "spago.lock",
            "yaml": k / "spago.yaml", "boundary": k / "BOUNDARY.md", "tables": k / "src" / "Kernel" / "Tables.purs",
            "bundle": root / "mod" / "hooks" / "kernel.js", "dts": root / "mod" / "hooks" / "kernel.d.ts",
            "core": root / "mod" / "hooks" / "core.ts"}


def rel(path: Path, root: Path = ROOT) -> str:
    try:
        return str(path.relative_to(root))
    except ValueError:
        return str(path)


def load_pin(root: Path = ROOT) -> dict:
    return json.loads(paths(root)["pin"].read_text(encoding="utf-8"))


def load_lock(root: Path = ROOT) -> dict:
    return json.loads(paths(root)["lock"].read_text(encoding="utf-8"))


def pin_id(root: Path = ROOT) -> str:
    p = paths(root)
    return hashlib.sha256(p["pin"].read_bytes() + b"\0" + p["lock"].read_bytes()).hexdigest()[:16]


def cache_base() -> Path:
    xdg = os.environ.get("XDG_CACHE_HOME", "")
    base = Path(xdg) if xdg and os.path.isabs(xdg) else Path.home() / ".cache"
    return base / "workbench" / "kernel"


def cache_dir(root: Path = ROOT, into: str | None = None) -> Path:
    return Path(into).expanduser().resolve() if into else cache_base() / pin_id(root)


def platform_key() -> str:
    """'linux-x64', 'darwin-arm64', …: the keys of toolchain.json's assets (WSL2 is linux)."""
    system = platform.system().lower()
    machine = platform.machine().lower()
    arch = {"x86_64": "x64", "amd64": "x64", "arm64": "arm64", "aarch64": "arm64"}.get(machine, machine)
    return f"{system}-{arch}"


# --- hashes and archives ------------------------------------------------------------------------

def sha256_hex(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sri(algo: str, data: bytes) -> str:
    return f"{algo}-" + base64.b64encode(hashlib.new(algo, data).digest()).decode()


def check_hash(data: bytes, entry: dict, what: str) -> None:
    """The archive against its pin: `sha256` hex (a GitHub release), `sha512` or `integrity` SRI
    (npm, spago.lock)."""
    if "sha256" in entry:
        got, want = sha256_hex(data), entry["sha256"]
    elif "sha512" in entry:
        got, want = sri("sha512", data), entry["sha512"]
    elif "integrity" in entry:
        algo = entry["integrity"].split("-", 1)[0]
        got, want = sri(algo, data), entry["integrity"]
    else:
        raise Refused(f"bad hash: {what} has no pinned hash")
    if got != want:
        raise Refused(f"bad hash: {what} hashes to {got}, the pin says {want}")


def _open_tar(data: bytes, what: str) -> tarfile.TarFile:
    try:
        return tarfile.open(fileobj=io.BytesIO(data), mode="r:*")
    except tarfile.TarError as e:
        raise Refused(f"{what} is not a readable archive: {e}") from None


def verify_member(data: bytes, member: str, bin_sha256: str, what: str = "the archive") -> bytes:
    """The one member, by its fixed name, as bytes: a regular file whose sha256 is the pin's."""
    with _open_tar(data, what) as tf:
        try:
            m = tf.getmember(member)
        except KeyError:
            raise Refused(f"{what} carries no {member}") from None
        if m.issym() or m.islnk():
            raise Refused(f"a link: {member} in {what} is a link, not the binary")
        if not m.isfile():
            raise Refused(f"{member} in {what} is not a regular file")
        body = tf.extractfile(m).read()
    if sha256_hex(body) != bin_sha256:
        raise Refused(f"bad hash: {member} in {what} hashes to {sha256_hex(body)}, the pin says {bin_sha256}")
    return body


def unpack(data: bytes, top: str, dest: Path, what: str = "the archive") -> None:
    """Every member under `top/` into dest: regular files and directories only. A link, a device,
    an absolute path, a `..` or a member outside `top/` refuses the whole archive, by name, and
    nothing the archive says about modes or owners is kept."""
    with _open_tar(data, what) as tf:
        members = tf.getmembers()
        for m in members:
            parts = PurePosixPath(m.name).parts
            if m.name.startswith("/") or ".." in parts or not parts or parts[0] != top:
                raise Refused(f"a path escape: {m.name!r} in {what} is not under {top}/")
            if m.issym() or m.islnk():
                raise Refused(f"a link: {m.name!r} in {what}")
            if not (m.isfile() or m.isdir()):
                raise Refused(f"not a regular file: {m.name!r} in {what}")
        for m in members:
            target = dest.joinpath(*PurePosixPath(m.name).parts)
            if m.isdir():
                target.mkdir(parents=True, exist_ok=True)
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(tf.extractfile(m).read())


def write_atomic(path: Path, data: bytes, mode: int | None = None) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.tmp-{os.getpid()}")
    tmp.write_bytes(data)
    if mode is not None:
        os.chmod(tmp, mode)
    os.replace(tmp, path)


def download(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "workbench-kernel/1"})
    with urllib.request.urlopen(req, timeout=180) as r:
        return r.read()


# --- the toolchain ------------------------------------------------------------------------------

def locked_packages(root: Path = ROOT) -> list[tuple[str, str, str]]:
    """(name, version, integrity) of every package spago.lock pins, registry packages only."""
    out = []
    for name, p in sorted(load_lock(root)["packages"].items()):
        if p.get("type") != "registry":
            raise Refused(f"spago.lock: {name} is a {p.get('type')} package; only registry ones are fetched")
        out.append((name, p["version"], p["integrity"]))
    return out


def tool_path(cache: Path, tool: str, pin: dict) -> Path:
    return cache / f"{tool}-{pin[tool]['version']}" / tool


def package_path(cache: Path, name: str, version: str) -> Path:
    return cache / "packages" / f"{name}-{version}.tar.gz"


def _fresh(path: Path, check) -> bool:
    if not path.is_file():
        return False
    try:
        check(path.read_bytes())
        return True
    except Refused:
        return False


def ensure(root: Path = ROOT, into: str | None = None, network: bool = True, say=print) -> Path:
    """The toolchain in the cache, each piece checked again; missing or wrong ones fetched when
    `network`, else refused. Returns the cache directory."""
    pin = load_pin(root)
    cache = cache_dir(root, into)
    key = platform_key()
    for tool in ("purs", "esbuild"):
        entry = pin[tool]["assets"].get(key)
        if not entry:
            raise Refused(f"no pinned {tool} for {key} (toolchain.json has {', '.join(sorted(pin[tool]['assets']))})")
        target = tool_path(cache, tool, pin)

        def bin_ok(b: bytes, want=entry["bin_sha256"], name=tool) -> None:
            if sha256_hex(b) != want:
                raise Refused(f"bad hash: the cached {name} hashes to {sha256_hex(b)}, the pin says {want}")
        if _fresh(target, bin_ok):
            continue
        if not network:
            raise Refused(f"{tool} {pin[tool]['version']} in {cache} is missing or not the pinned one: "
                          "run python3 scripts/kernel.py fetch")
        say(f"kernel: fetching {tool} {pin[tool]['version']} ({entry['url']})")
        data = download(entry["url"])
        check_hash(data, entry, entry["url"])
        write_atomic(target, verify_member(data, pin[tool]["member"], entry["bin_sha256"], entry["url"]), 0o755)
    registry = pin["registry"]
    for name, version, integrity in locked_packages(root):
        target = package_path(cache, name, version)
        what = f"{name}-{version}.tar.gz"
        if _fresh(target, lambda b, w=what, i=integrity: check_hash(b, {"integrity": i}, w)):
            continue
        if not network:
            raise Refused(f"{what} in {cache} is missing or not the locked one: run python3 scripts/kernel.py fetch")
        url = f"{registry}{name}/{version}.tar.gz"
        say(f"kernel: fetching {url}")
        data = download(url)
        check_hash(data, {"integrity": integrity}, url)
        with tempfile.TemporaryDirectory() as scratch:  # refused now, not at the first build
            unpack(data, f"{name}-{version}", Path(scratch), url)
        write_atomic(target, data)
    return cache


# --- Tables: Python's constants, one way ---------------------------------------------------------

def tables_values() -> dict:
    """What Kernel.Tables copies from workbench's Python, in field order: the phase sets
    (store.py), the opening of ask_mcp.NO_ANSWER (how the mod tells a timed-out question from an
    answered one), how long a chat listener counts as there (chat.LISTENING_FOR, in ms) and the
    opening of the mod's wakes (spend.WAKE_OPENING, which spend.WAKE matches)."""
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    from workbench import ask_mcp, chat, spend, store
    return {
        "active": sorted(store.ACTIVE),
        "needsClaude": sorted(store.NEEDS_CLAUDE),
        "parks": sorted(store.PARKS),
        "closed": sorted(store.CLOSED),
        "noAnswer": ask_mcp.NO_ANSWER.split(". ", 1)[0] + ".",
        "chatStaleMs": float(chat.LISTENING_FOR * 1000),
        "wakeOpening": spend.WAKE_OPENING,
    }


def purs_string(s: str) -> str:
    out = []
    for ch in s:
        if ch in '"\\':
            out.append("\\" + ch)
        elif " " <= ch <= "~":
            out.append(ch)
        else:
            out.append("\\x" + format(ord(ch), "06x"))  # six digits: no hex letter after it is read in
    return '"' + "".join(out) + '"'


def _purs_field(value) -> tuple[str, str]:
    if isinstance(value, bool):
        return "Boolean", "true" if value else "false"
    if isinstance(value, float):
        return "Number", repr(value)
    if isinstance(value, str):
        return "String", purs_string(value)
    if isinstance(value, list) and all(isinstance(v, str) for v in value):
        return "Array String", "[ " + ", ".join(purs_string(v) for v in value) + " ]" if value else "[]"
    raise Refused(f"tables: {value!r} has no wire type (a list of strings, a string, a float, a bool)")


def tables_source(values: dict | None = None) -> str:
    values = tables_values() if values is None else values
    fields = [(k, *_purs_field(v)) for k, v in values.items()]
    sig = "\n".join(f"  :: {{ {k} :: {t}" if i == 0 else f"     , {k} :: {t}" for i, (k, t, _) in enumerate(fields))
    body = "\n".join(f"  {'{' if i == 0 else ','} {k}: {v}" for i, (k, _, v) in enumerate(fields))
    return (TABLES_HEAD + "module Kernel.Tables (tables) where\n\n"
            "tables\n" + sig + "\n     }\ntables =\n" + body + "\n  }\n")


def tables(root: Path = ROOT, check: bool = False) -> bool:
    """Writes Tables.purs from the Python; with check, writes nothing and says whether it holds."""
    target = paths(root)["tables"]
    want = tables_source()
    have = target.read_text(encoding="utf-8") if target.exists() else ""
    if have == want:
        return True
    if check:
        return False
    write_atomic(target, want.encode())
    return True


# --- lint ---------------------------------------------------------------------------------------

def denied(module: str) -> bool:
    for p in DENIED:
        if p.endswith(".*"):
            if module == p[:-2] or module.startswith(p[:-1]):
                return True
        elif p.endswith("*"):
            if module.startswith(p[:-1]):
                return True
        elif module == p:
            return True
    return False


def purs_files(root: Path = ROOT) -> list[Path]:
    return sorted(paths(root)["src"].rglob("*.purs"))


def test_files(root: Path = ROOT) -> list[Path]:
    """kernel/test's PureScript: the props, held to kernel/src's lint but outside its digest and
    budget, as nothing in them reaches the bundle."""
    return sorted(paths(root)["test"].rglob("*.purs"))


# Read over the whole file, not line by line: PureScript lets `import` end a line and the module
# name start the next, and a per-line match passed `import\n  Effect.Unsafe (…)` (the 2026-11-25
# review of #1356's scaffolding)
SRC_FOREIGN = re.compile(r"(?m)^[ \t]*foreign\s+import\b")
SRC_IMPORT = re.compile(r"(?m)^[ \t]*import\s+([A-Z][\w.]*)")
SYMBOL = set(":!#$%&*+./<=>?@\\^|-~")  # after `--` they make an operator, not a comment


def uncommented(text: str) -> str:
    """The text with its comments (`--` to the line's end, `{- -}` nested) blanked to spaces, the
    newlines kept, so a match's offset is the same line in both. `import {- -} Effect.Unsafe` passed
    the per-text lint (2026-11-25, the adversarial review of #1356); only the corefn caught it."""
    out, i, n = [], 0, len(text)
    while i < n:
        if text.startswith("{-", i):
            depth, j = 1, i + 2
            while j < n and depth:
                if text.startswith("{-", j):
                    depth, j = depth + 1, j + 2
                elif text.startswith("-}", j):
                    depth, j = depth - 1, j + 2
                else:
                    j += 1
        elif text.startswith("--", i):
            j = i
            while j < n and text[j] == "-":
                j += 1
            if j < n and text[j] in SYMBOL:
                out.append(text[i:j])
                i = j
                continue
            j = text.find("\n", i)
            j = n if j < 0 else j
        else:
            out.append(text[i])
            i += 1
            continue
        out.append(re.sub(r"[^\n]", " ", text[i:j]))
        i = j
    return "".join(out)


def lint_sources(root: Path = ROOT) -> list[str]:
    """kernel/src and kernel/test as text: no foreign import, no denied import, no locale call.
    Read as written and with the comments blanked, each finding once: a comment can't hide one,
    and a stray `{-` in a string can't either."""
    errors = []
    for f in [*purs_files(root), *test_files(root)]:
        text = f.read_text(encoding="utf-8")
        at = lambda i: f"{rel(f, root)}:{text.count(chr(10), 0, i) + 1}"  # noqa: E731
        both = (text, uncommented(text))
        for start in sorted({m.start() for t in both for m in SRC_FOREIGN.finditer(t)}):
            errors.append(f"{at(start)}: a foreign import; kernel/src has no FFI (kernel/BOUNDARY.md)")
        for start, name in sorted({(m.start(), m.group(1)) for t in both for m in SRC_IMPORT.finditer(t)}):
            if denied(name):
                errors.append(f"{at(start)}: imports {name}, denied (kernel/BOUNDARY.md, *Denied imports*)")
        for n, line in enumerate(text.splitlines(), 1):
            for word in DENIED_TEXT:
                if word in line:
                    errors.append(f"{rel(f, root)}:{n}: {word} is locale-dependent, denied (kernel/BOUNDARY.md)")
    return errors


def lint_corefn(output: Path) -> list[str]:
    """The compiler's view of every module compiled from kernel/src or kernel/test (its corefn's
    modulePath under src/ or test/, whatever the module is called; the packages' own are theirs):
    no foreign declarations, no denied import (the compiler's own, such as Data.Eq for ==,
    included). Only Kernel.* was read, and a helper module named otherwise imported Effect.Unsafe
    past it (the 2026-11-25 review)."""
    errors = []
    for f in sorted(output.glob("*/corefn.json")):
        core = json.loads(f.read_text(encoding="utf-8"))
        if not core.get("modulePath", "").startswith(("src/", "test/")):
            continue
        mod = ".".join(core["moduleName"])
        if core.get("foreign"):
            errors.append(f"{mod}: foreign {', '.join(core['foreign'])}; kernel/src has no FFI")
        for imp in core.get("imports", []):
            name = ".".join(imp["moduleName"])
            if denied(name):
                errors.append(f"{mod}: imports {name}, denied (kernel/BOUNDARY.md, *Denied imports*)")
    return errors


# --- the typed surface --------------------------------------------------------------------------

def _qname(t: dict) -> str:
    c = t["contents"]
    return ".".join(c[0]) + "." + c[1]


def type_name(t: dict) -> str:
    tag = t.get("tag")
    if tag == "TypeConstructor":
        return _qname(t)
    if tag == "TypeApp":
        return type_name(t["contents"][0])
    if tag == "ForAll":
        return "a forall"
    if tag == "TypeVar":
        return f"the type variable {t['contents']}"
    return str(tag)


def _con(t: dict, name: str) -> bool:
    return t.get("tag") == "TypeConstructor" and _qname(t) == name


def _unparen(t: dict) -> dict:
    while t.get("tag") in ("ParensInType", "KindedType"):
        t = t["contents"] if t["tag"] == "ParensInType" else t["contents"][0]
    return t


def _resolve(t: dict, syn: dict) -> dict:
    t = _unparen(t)
    seen = set()
    while t.get("tag") == "TypeConstructor" and _qname(t) in syn and _qname(t) not in seen:
        seen.add(_qname(t))
        t = _unparen(syn[_qname(t)])
    return t


def _label(label: str) -> str:
    return label if re.fullmatch(r"[A-Za-z_$][\w$]*", label) else json.dumps(label)


def wire_ts(t: dict, syn: dict, where: str, indent: int = 0) -> str:
    """A wire type in TypeScript: Number, String, Boolean, Array and closed records, nothing else
    (kernel/BOUNDARY.md, *Wire types*). Raises NotWire naming the export and the type."""
    t = _resolve(t, syn)
    tag = t.get("tag")
    if tag == "TypeConstructor" and _qname(t) in PRIM:
        return PRIM[_qname(t)]
    if tag == "TypeApp":
        f, a = t["contents"]
        f = _resolve(f, syn)
        if _con(f, "Prim.Array"):
            return f"ReadonlyArray<{wire_ts(a, syn, where, indent)}>"
        if _con(f, "Prim.Record"):
            row, fields = _resolve(a, syn), []
            while row.get("tag") == "RCons":
                label, ty, rest = row["contents"]
                fields.append((label, ty))
                row = _resolve(rest, syn)
            if row.get("tag") != "REmpty":
                raise NotWire(f"{where}: an open row ({type_name(row)}); a wire record is closed")
            if not fields:
                return "{}"
            pad = "  " * (indent + 1)
            inner = "".join(f"{pad}readonly {_label(k)}: {wire_ts(v, syn, f'{where}.{k}', indent + 1)}\n"
                            for k, v in fields)
            return "{\n" + inner + "  " * indent + "}"
    raise NotWire(f"{where}: {type_name(t)} is not a wire type (Number, String, Boolean, Array, a closed record)")


def docs_index(output: Path) -> tuple[dict, dict]:
    """The kernel modules' value declarations by name, and their type synonyms by qualified name,
    from purs's docs.json (Kernel.Main only re-exports)."""
    values, syn = {}, {}
    for f in sorted(output.glob("Kernel.*/docs.json")):
        doc = json.loads(f.read_text(encoding="utf-8"))
        for d in doc.get("declarations", []):
            info = d.get("info", {})
            if info.get("declType") == "value":
                values[d["title"]] = (doc["name"], info["type"])
            elif info.get("declType") == "typeSynonym" and not info.get("arguments"):
                syn[f"{doc['name']}.{d['title']}"] = info["type"]
    return values, syn


def export_dts(name: str, t: dict, syn: dict) -> str:
    r = _resolve(t, syn)
    if r.get("tag") == "TypeApp":
        f = _resolve(r["contents"][0], syn)
        if f.get("tag") == "TypeApp" and _con(_resolve(f["contents"][0], syn), "Prim.Function"):
            arg = _resolve(f["contents"][1], syn)
            if not (arg.get("tag") == "TypeApp" and _con(_resolve(arg["contents"][0], syn), "Prim.Record")):
                raise NotWire(f"{name}: takes {type_name(arg)}; a decision takes one record of facts")
            return (f"export declare function {name}(facts: {wire_ts(arg, syn, name + '(facts)')}): "
                    f"{wire_ts(r['contents'][1], syn, name + '()')}\n")
    return f"export declare const {name}: {wire_ts(r, syn, name)}\n"


def dts(output: Path, names: list[str]) -> bytes:
    values, syn = docs_index(output)
    out = ["// The kernel's typed surface, written from purs's docs.json by scripts/kernel.py build: only\n"
           "// mod/hooks/core.ts imports ./kernel.js (kernel/BOUNDARY.md, *Membrane*).\n"]
    for name in names:
        if name not in values:
            raise Refused(f"the bundle exports {name}, which no kernel module declares")
        out.append(export_dts(name, values[name][1], syn))
    return "".join(out).encode()


def bundle_exports(body: bytes | str) -> list[str]:
    """The names in the bundle's closing `export { … };`, as esbuild writes it."""
    text = body.decode() if isinstance(body, bytes) else body
    m = re.search(r"export\s*\{([^}]*)\};?\s*\Z", text)
    if not m:
        return []
    names = []
    for part in m.group(1).split(","):
        part = part.strip()
        if part:
            names.append(part.split(" as ")[-1].strip())
    return names


def dts_exports(text: str) -> list[str]:
    return re.findall(r"(?m)^export declare (?:const|function) (\w+)", text)


# --- the build ----------------------------------------------------------------------------------

def inputs_digest(root: Path = ROOT) -> str:
    """sha256 over the sorted kernel/src/**/*.purs, toolchain.json and spago.lock, each as its
    path, a NUL, its bytes and a NUL: what a build is a function of."""
    p = paths(root)
    files = sorted([*purs_files(root), p["pin"], p["lock"]], key=lambda f: rel(f, root))
    h = hashlib.sha256()
    for f in files:
        h.update(rel(f, root).encode() + b"\0" + f.read_bytes() + b"\0")
    return h.hexdigest()


def banner(inputs: str, body: bytes, pin: dict) -> bytes:
    return BANNER.format(inputs=inputs, body=sha256_hex(body), purs=pin["purs"]["version"],
                         esbuild=pin["esbuild"]["version"]).encode()


def read_banner(data: bytes) -> tuple[str, str, str, str] | None:
    line, _, _ = data.partition(b"\n")
    m = BANNER_RE.fullmatch(line.decode(errors="replace") + "\n")
    return m.groups() if m else None


def _run(argv: list[str], cwd: Path, what: str) -> None:
    r = subprocess.run(argv, cwd=cwd, capture_output=True, text=True)
    if r.returncode:
        # purs writes its errors to stdout and its progress to stderr, so stderr's tail showed only
        # "[n of m] Compiling …" lines and never the error (the 2026-11-25 review); esbuild writes
        # its errors to stderr and nothing to stdout. purs's first error is the one to read: its head
        out = r.stdout.strip().splitlines()[:60] or r.stderr.strip().splitlines()[-30:]
        raise Refused(f"{what} failed (exit {r.returncode}):\n" + "\n".join(out))


def purs_compile(root: Path, cache: Path, work: Path, tests: bool = False) -> None:
    """kernel/src (and kernel/test, with `tests`) and the locked packages compiled into
    `work/output`, its corefn linted. The sources are copied in and the output directory is always
    `work/output`, because esbuild writes its relative path into the bundle: the same bytes from
    any clone, on any machine."""
    pin = load_pin(root)
    for name, version, integrity in locked_packages(root):
        data = package_path(cache, name, version).read_bytes()
        check_hash(data, {"integrity": integrity}, f"{name}-{version}.tar.gz")
        unpack(data, f"{name}-{version}", work / "packages", f"{name}-{version}.tar.gz")
    shutil.copytree(paths(root)["src"], work / "src")
    globs = ["packages/*/src/**/*.purs", "src/**/*.purs"]
    if tests:
        shutil.copytree(paths(root)["test"], work / "test")
        globs.append("test/**/*.purs")
    _run([str(tool_path(cache, "purs", pin)), "compile", "-g", "js,docs,corefn", "-o", "output", *globs],
         work, "purs compile")
    errors = lint_corefn(work / "output")
    if errors:
        raise Refused("lint:\n" + "\n".join(errors))


def compile_kernel(root: Path, cache: Path, work: Path) -> tuple[bytes, bytes]:
    """kernel/src compiled and bundled in `work`: returns (kernel.js, kernel.d.ts), bannered."""
    pin = load_pin(root)
    purs_compile(root, cache, work)
    _run([str(tool_path(cache, "esbuild", pin)), "output/Kernel.Main/index.js", *pin["esbuild"]["flags"],
          "--outfile=kernel.js", "--log-level=warning"], work, "esbuild")
    body = (work / "kernel.js").read_bytes()
    names = bundle_exports(body)
    if not names:
        raise Refused("the bundle exports nothing: Kernel.Main re-exports the kernel's exports")
    surface = dts(work / "output", names)
    inputs = inputs_digest(root)
    return banner(inputs, body, pin) + body, banner(inputs, surface, pin) + surface


def build(root: Path = ROOT, into: str | None = None, write: bool = True) -> tuple[bytes, bytes]:
    tables(root)
    cache = ensure(root, into)
    with tempfile.TemporaryDirectory(prefix="wb-kernel-") as work:
        js, surface = compile_kernel(root, cache, Path(work))
    if write:
        p = paths(root)
        write_atomic(p["bundle"], js)
        write_atomic(p["dts"], surface)
    return js, surface


# --- the props -----------------------------------------------------------------------------------

PROPS_TEST = "props.test.ts"


def bun() -> tuple[str, dict[str, str]]:
    """Bun here, and the environment it wants: bun itself, else OpenCode's own Bun (BUN_BE_BUN=1,
    which OpenCode 2.3.0 and 2.4.1 honour). Neither is a refusal by name, never a skip."""
    found = shutil.which("bun")
    if found:
        return found, {}
    opencode = shutil.which("opencode")
    if opencode:
        return opencode, {"BUN_BE_BUN": "1"}
    raise Refused("props need Bun: neither bun nor opencode (whose Bun runs them, BUN_BE_BUN=1 opencode test) "
                  "is on PATH; install either")


def props(root: Path = ROOT, into: str | None = None, say=print) -> str:
    """kernel/test/Props.purs compiled with kernel/src, bundled beside a scratch copy of
    props.test.ts, and run under Bun. Returns Bun's summary; a failure raises with Bun's report."""
    runner, env = bun()
    pin = load_pin(root)
    cache = ensure(root, into, say=say)
    with tempfile.TemporaryDirectory(prefix="wb-kernel-props-") as work:
        w = Path(work)
        purs_compile(root, cache, w, tests=True)
        _run([str(tool_path(cache, "esbuild", pin)), "output/Props/index.js", *pin["esbuild"]["flags"],
              "--outfile=test/props.js", "--log-level=warning"], w, "esbuild")
        r = subprocess.run([runner, "test", f"./test/{PROPS_TEST}"], cwd=w, env={**os.environ, **env},
                           capture_output=True, text=True, timeout=300)
    report = (r.stdout + r.stderr).strip()
    if r.returncode:
        raise Refused(f"props failed (exit {r.returncode}):\n" + "\n".join(report.splitlines()[-60:]))
    return " ".join(line.strip() for line in report.splitlines() if re.match(r"\s*\d+ (pass|fail)\b", line))


# --- the contract -------------------------------------------------------------------------------

def section(text: str, heading: str) -> str:
    m = re.search(rf"(?ms)^{re.escape(heading)}\n(.*?)(?=^## |\Z)", text)
    return m.group(1) if m else ""


def table_rows(block: str) -> list[list[str]]:
    rows = []
    for line in block.splitlines():
        if line.startswith("|") and not re.match(r"\|\s*-", line):
            rows.append([c.strip() for c in line.strip().strip("|").split("|")])
    return rows[1:]  # the header row


def boundary_exports(root: Path = ROOT) -> list[str]:
    text = paths(root)["boundary"].read_text(encoding="utf-8")
    return [r[0].strip("`") for r in table_rows(section(text, "## Exports"))]


def boundary_budget(root: Path = ROOT) -> dict[str, int]:
    text = paths(root)["boundary"].read_text(encoding="utf-8")
    return {r[0].strip("`"): int(r[1].replace(",", "")) for r in table_rows(section(text, "## Budget"))}


def boundary_denied(root: Path = ROOT) -> list[str]:
    text = paths(root)["boundary"].read_text(encoding="utf-8")
    para = re.search(r"(?ms)^Denied: (.*?)(?:\n\n|\Z)", section(text, "## Denied imports"))
    return re.findall(r"`([^`]+)`", para.group(1)) if para else []


def module_lines(root: Path = ROOT) -> dict[str, int]:
    p = paths(root)
    return {rel(f, root): len(f.read_text(encoding="utf-8").splitlines())
            for f in purs_files(root) if f != p["tables"]}


def budget_errors(root: Path = ROOT, bundle: bytes | None = None) -> list[str]:
    """kernel/BOUNDARY.md's `## Budget`, held: raised only by an edit to it that names the move."""
    p, b, errors = paths(root), boundary_budget(root), []
    bundle = p["bundle"].read_bytes() if bundle is None else bundle
    n = len(bundle_exports(bundle))
    if n > b["exports"]:
        errors.append(f"budget: {n} exports, over {b['exports']}")
    if len(bundle) > b["kernel.js bytes"]:
        errors.append(f"budget: kernel.js is {len(bundle):,} bytes, over {b['kernel.js bytes']:,}")
    lines = module_lines(root)
    if sum(lines.values()) > b["kernel/src lines"]:
        errors.append(f"budget: kernel/src is {sum(lines.values())} lines (Tables aside), over {b['kernel/src lines']}")
    errors += [f"budget: {f} is {n} lines, over {b['module lines']}" for f, n in lines.items() if n > b["module lines"]]
    if p["core"].exists():
        n = len(p["core"].read_text(encoding="utf-8").splitlines())
        if n > b["core.ts lines"]:
            errors.append(f"budget: mod/hooks/core.ts is {n} lines, over {b['core.ts lines']}")
    return errors


GOLDEN_FN = re.compile(r"""\bfn:\s*['"](\w+)['"]""")
KERNEL_IMPORT = re.compile(r"""(?:\bfrom|\bimport)\s*\(?\s*['"](?:[^'"]*/)?kernel(?:\.js)?['"]""")
HOST_DIRS = ("mod", "opencode-plugin", "workbench/chat_static")
DEFINES = r"(?m)^\s*(?:export )?(?:async )?(?:function|const|let|var|class) {name}\b"


def golden_files(root: Path = ROOT) -> list[Path]:
    return sorted(f for f in (root / "mod" / "hooks" / "golden").glob("*.ts") if f.name not in ("run.ts", "index.ts"))


def golden_fns(root: Path = ROOT) -> list[str]:
    return sorted({fn for f in golden_files(root) for fn in GOLDEN_FN.findall(f.read_text(encoding="utf-8"))})


def kernel_importers(root: Path = ROOT) -> list[str]:
    """Every host file that imports kernel.js, by repo path."""
    found = []
    for d in HOST_DIRS:
        for f in sorted((root / d).rglob("*")):
            if f.suffix in (".ts", ".tsx", ".js", ".mjs") and f.name not in ("kernel.js", "kernel.d.ts") \
                    and "node_modules" not in f.parts and KERNEL_IMPORT.search(f.read_text(encoding="utf-8", errors="replace")):
                found.append(rel(f, root))
    return found


def replaced_still_defined(root: Path = ROOT) -> list[str]:
    """`## Exports`' `replaces` names that are still defined where they were (`<file>:<name>`) or
    still in wb (`wb:<mod.attr>`): a move deletes the old copy in the same commit."""
    text = paths(root)["boundary"].read_text(encoding="utf-8")
    out = []
    for row in table_rows(section(text, "## Exports")):
        for item in re.findall(r"(born:#\d+|wb:[\w.]+|[\w./-]+\.\w+:\w+)", row[3] if len(row) > 3 else ""):
            if item.startswith("born:"):
                continue
            if item.startswith("wb:"):
                mod, _, attr = item[3:].rpartition(".")
                f = root / "workbench" / (mod.replace(".", "/") + ".py")
                if f.exists() and re.search(rf"(?m)^(?:def |class )?{re.escape(attr)}\b", f.read_text(encoding="utf-8")):
                    out.append(item)
                continue
            file, _, name = item.rpartition(":")
            f = root / file
            if f.exists() and re.search(DEFINES.format(name=re.escape(name)), f.read_text(encoding="utf-8")):
                out.append(item)
    return out


def phase_literals(root: Path = ROOT) -> list[str]:
    """Phases spelled out in opencode-plugin/: it reads them from core.ts, never a copy of its own."""
    v = tables_values()
    phases = sorted({*v["active"], *v["needsClaude"], *v["closed"]})
    pat = re.compile(r"""['"`](%s)['"`]""" % "|".join(map(re.escape, phases)))
    out = []
    for f in sorted((root / "opencode-plugin").rglob("*.ts")):
        if "node_modules" in f.parts:
            continue
        for n, line in enumerate(f.read_text(encoding="utf-8").splitlines(), 1):
            if pat.search(line):
                out.append(f"{rel(f, root)}:{n}")
    return out


def offline_errors(root: Path = ROOT) -> list[str]:
    """What holds without the toolchain (tests/test_kernel.py runs it in `python3 -m unittest`):
    the lint of kernel/src, Tables against the Python, the banners' digests, the bundle's scan, one
    set of exports in BOUNDARY.md, the bundle, the d.ts and the goldens, one importer, no replaced
    name left, no phase literal in the plugin, the budgets. Each line names its fix."""
    p, pin, errors = paths(root), load_pin(root), lint_sources(root)
    fix = "run python3 scripts/kernel.py build"
    if not tables(root, check=True):
        errors.append(f"kernel/src/Kernel/Tables.purs is not what workbench's Python says: {fix}")
    inputs = inputs_digest(root)
    for target in (p["bundle"], p["dts"]):
        name = rel(target, root)
        data = target.read_bytes() if target.exists() else b""
        got = read_banner(data)
        if not got:
            errors.append(f"{name} has no banner on its first line: {fix}")
            continue
        was, body, purs, esbuild = got
        if body != sha256_hex(data.partition(b"\n")[2]):
            errors.append(f"{name} was edited by hand (its body is not the one its banner names): {fix}")
        if was != inputs:
            errors.append(f"{name} is stale: kernel/src, toolchain.json or spago.lock changed since it was built: {fix}")
        if (purs, esbuild) != (pin["purs"]["version"], pin["esbuild"]["version"]):
            errors.append(f"{name} was built by purs {purs} and esbuild {esbuild}, not the pinned ones: {fix}")
    js = p["bundle"].read_text(encoding="utf-8") if p["bundle"].exists() else ""
    held = [t for t in BUNDLE_DENIED if t in js]
    if held:
        errors.append(f"mod/hooks/kernel.js holds {', '.join(held)}: the kernel has no effects, host, clock, "
                      "chance or locale (kernel/BOUNDARY.md)")
    surface = p["dts"].read_text(encoding="utf-8") if p["dts"].exists() else ""
    sets = {"kernel/BOUNDARY.md's `## Exports`": sorted(boundary_exports(root)),
            "mod/hooks/kernel.js": sorted(bundle_exports(js)), "mod/hooks/kernel.d.ts": sorted(dts_exports(surface)),
            "the goldens (mod/hooks/golden/)": golden_fns(root)}
    if len({tuple(v) for v in sets.values()}) > 1:
        errors.append("the exports differ: " + "; ".join(f"{k} {v}" for k, v in sets.items())
                      + ": an export has its row, its golden cases and a build")
    index = root / "mod" / "hooks" / "golden" / "index.ts"
    listed = index.read_text(encoding="utf-8") if index.exists() else ""
    for f in golden_files(root):
        if f"'./{f.stem}.js'" not in listed:
            errors.append(f"mod/hooks/golden/{f.name} is not in golden/index.ts's GOLDENS: neither host runs it")
    others = [f for f in kernel_importers(root) if f != "mod/hooks/core.ts"]
    if others:
        errors.append(f"{', '.join(others)} imports kernel.js: only mod/hooks/core.ts does (kernel/BOUNDARY.md, *Membrane*)")
    errors += [f"{item} is still defined: the move that replaces it deletes it" for item in replaced_still_defined(root)]
    errors += [f"{where}: a phase literal; the plugin reads phases from core.ts" for where in phase_literals(root)]
    errors += budget_errors(root)
    return errors


def check(root: Path = ROOT, into: str | None = None, say=print) -> list[str]:
    """CI's kernel job: everything that must hold, each failure named with its fix."""
    p = paths(root)
    errors = offline_errors(root)
    cache = ensure(root, into, say=say)
    builds = []
    for _ in range(2):
        with tempfile.TemporaryDirectory(prefix="wb-kernel-") as work:
            builds.append(compile_kernel(root, cache, Path(work)))
    if builds[0] != builds[1]:
        errors.append("two builds of kernel/src differ: the build is not deterministic")
    js, surface = builds[0]
    stale = False
    for target, want in ((p["bundle"], js), (p["dts"], surface)):
        have = target.read_bytes() if target.exists() else b""
        if have != want:
            stale = True
            errors.append(f"{rel(target, root)} is not what kernel/src builds: run python3 scripts/kernel.py build")
    if stale:  # the offline checks read the committed bundle; these read the one the source builds
        if sorted(bundle_exports(js)) != sorted(boundary_exports(root)):
            errors.append(f"the source builds exports {bundle_exports(js)}, kernel/BOUNDARY.md's `## Exports` "
                          f"lists {boundary_exports(root)}: a new export gets its row, a removed one loses it")
        errors += budget_errors(root, js)
    try:
        props(root, into, say=say)
    except Refused as e:
        errors.append(str(e))
    return list(dict.fromkeys(errors))


# --- re-locking ---------------------------------------------------------------------------------

def relock(root: Path = ROOT, into: str | None = None, say=print) -> None:
    """spago.lock from spago.yaml, by the pinned spago: npm installs it into the cache (no install
    scripts), and it resolves in a scratch copy of spago.yaml with the pinned purs, its own cache
    under ours. Then fetch the new lock's packages and build."""
    pin = load_pin(root)
    npm = shutil.which("npm")
    if not npm:
        raise Refused("relock needs npm (Node.js) for spago; builds never do")
    cache = ensure(root, into, say=say)
    base = cache_base()
    spago_home = base / f"spago-{pin['spago']['version']}"
    spago = spago_home / "node_modules" / ".bin" / "spago"
    if not spago.exists():
        say(f"kernel: installing spago {pin['spago']['version']} from npm into {spago_home}")
        _run([npm, "install", "--prefix", str(spago_home), "--ignore-scripts", "--no-audit", "--no-fund",
              "--no-save", f"spago@{pin['spago']['version']}"], base, "npm install spago")
    env = {**os.environ, "XDG_CACHE_HOME": str(base / "spago-home"),
           "PATH": f"{tool_path(cache, 'purs', pin).parent}{os.pathsep}{os.environ.get('PATH', '')}"}
    with tempfile.TemporaryDirectory(prefix="wb-relock-") as work:
        shutil.copy(paths(root)["yaml"], Path(work) / "spago.yaml")
        r = subprocess.run([str(spago), "install"], cwd=work, env=env, capture_output=True, text=True)
        if r.returncode:
            raise Refused(f"spago install failed (exit {r.returncode}):\n{(r.stderr or r.stdout)[-3000:]}")
        write_atomic(paths(root)["lock"], (Path(work) / "spago.lock").read_bytes())
    say("kernel: wrote kernel/spago.lock; run python3 scripts/kernel.py build")


# --- the command --------------------------------------------------------------------------------

def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(prog="kernel.py", description=__doc__.split("\n\n")[0])
    ap.add_argument("command", choices=("fetch", "tables", "build", "lint", "props", "check", "relock"))
    ap.add_argument("--check", action="store_true", help="tables: fail when stale, write nothing")
    ap.add_argument("--into", metavar="DIR", help="the toolchain's directory instead of the cache")
    a = ap.parse_args(argv)
    try:
        if a.command == "fetch":
            cache = ensure(ROOT, a.into)
            print(f"kernel: toolchain verified in {cache}")
        elif a.command == "tables":
            if not tables(ROOT, check=a.check):
                raise Refused("kernel/src/Kernel/Tables.purs is not what workbench's Python says: "
                              "run python3 scripts/kernel.py build")
            print("kernel: Tables.purs is what the Python says")
        elif a.command == "build":
            js, _ = build(ROOT, a.into)
            print(f"kernel: wrote mod/hooks/kernel.js ({len(js):,} bytes, exports "
                  f"{', '.join(bundle_exports(js))}) and mod/hooks/kernel.d.ts")
        elif a.command == "lint":
            errors = lint_sources(ROOT)
            if not errors:
                cache = ensure(ROOT, a.into)
                with tempfile.TemporaryDirectory(prefix="wb-kernel-") as work:
                    compile_kernel(ROOT, cache, Path(work))  # refuses on a corefn finding
            if errors:
                raise Refused("lint:\n" + "\n".join(errors))
            print("kernel: lint clean (source and corefn)")
        elif a.command == "props":
            print(f"kernel: props passed ({props(ROOT, a.into)})")
        elif a.command == "check":
            errors = check(ROOT, a.into)
            if errors:
                raise Refused("check:\n" + "\n".join(errors))
            print(f"kernel: check passed: lint, Tables, two identical builds equal to the commit, "
                  f"exports, budgets ({paths()['bundle'].stat().st_size:,} bytes), props")
        elif a.command == "relock":
            relock(ROOT, a.into)
    except Refused as e:
        print(f"kernel: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
