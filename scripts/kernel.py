#!/usr/bin/env python3
"""scripts/kernel.py: the PureScript kernel's toolchain, build and checks (kernel/BOUNDARY.md, #1356).

  fetch             the pinned purs and esbuild (kernel/toolchain.json) and spago.lock's packages,
                    each checked against its pinned hash, into the per-user cache
  tables [--check]  write kernel/src/Kernel/Tables.purs from workbench's Python (--check: fail
                    when it is not what the Python says, writing nothing)
  build             tables, then compile kernel/src and bundle it into mod/hooks/kernel.js and its
                    typed surface mod/hooks/kernel.d.ts, both committed
  lint              kernel/src's imports and FFI: the source, then the compiler's corefn
  props             kernel/test/Props.purs's seeded properties, compiled with kernel/src and run
                    under Bun (bun, else OpenCode's: BUN_BE_BUN=1 opencode test)
  check             lint, tables --check, two builds byte-equal to each other and to the commit,
                    the exports against BOUNDARY.md, the budgets, the props (CI's kernel job)
  relock            re-lock kernel/spago.lock with the pinned spago (needs npm; a contributor's
                    step after editing spago.yaml, never CI's)
  --into DIR        keep the toolchain in DIR instead of the cache

The cache is ${XDG_CACHE_HOME:-~/.cache}/workbench/kernel/<pin>/, <pin> a digest of toolchain.json
and spago.lock, so every worktree shares one copy and a bump never reads an old one. A cached copy
is checked again on every run, offline: the binaries against bin_sha256, the package tarballs
against the lock. Nothing is installed anywhere else, and users need none of it: the committed
bundle is what the mod loads.

Standard library only, Python 3.11. Archives are read member by member: only regular files and
directories under the one top directory are written, never a link, never a path that escapes.
"""
