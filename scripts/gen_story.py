#!/usr/bin/env python3
"""scripts/gen_story.py: the story's generated copies (#1355), from workbench/story.py, the one
source of every sentence the chat and the docs tell the user about the driver and the chat.

  (no argument)   write workbench/chat_static/src/story.ts (the web app's tables and fill, which
                  scripts/web.py then builds into story.js), mod/hooks/story.ts (the hosts' texts,
                  story.HOST filled for each host: the Claude Code mod and the OpenCode plugin
                  import it) and fill the doc blocks (`<!-- story:KEY[:driver] -->` …
                  `<!-- /story -->`) story.DOCS names
  --check         write nothing: exit 1 naming each copy that isn't what this would write (CI's,
                  through tests/test_story.py)

Standard library only, Python 3.11.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from workbench import story  # noqa: E402

PAGE_TS = ROOT / "workbench" / "chat_static" / "src" / "story.ts"
HOST_TS = ROOT / "mod" / "hooks" / "story.ts"
# the host module's table name for each host
HOST_NAMES = {"claude-code": "CLAUDE_CODE", "opencode": "OPENCODE"}
BANNER = "// Generated by scripts/gen_story.py from workbench/story.py: do not edit; run python3 scripts/gen_story.py.\n"
BLOCK = re.compile(r"(<!-- story:([a-z.]+)(?::([a-z-]+))? -->\n)(.*?)(<!-- /story -->)", re.S)

# The page's fill: story.fill's rules, `{name}` from the fields, `{Name}` capitalized, a name
# missing kept as written with `partial` (else thrown). tests/fixtures/story/fill.json holds both.
FILL_TS = """\
function storyFill(t: string, fields: Record<string, string>, partial = false): string {
  return t.replace(/\\{([A-Za-z_]+)\\}/g, (all: string, name: string) => {
    const low = name.charAt(0).toLowerCase() + name.slice(1)
    if (Object.prototype.hasOwnProperty.call(fields, low)) {
      const v = String(fields[low])
      return name !== low ? v.charAt(0).toUpperCase() + v.slice(1) : v
    }
    if (partial) return all
    throw new Error('story: no field ' + name)
  })
}
// One of the page's sentences for the driver (`claude-code`, `opencode`, `any`), the fields the
// caller has beside the driver's own; one it lacks stays as written
function storyText(key: string, driver: string = 'any', fields: Record<string, string> = {}): string {
  const t = STORY_TEXTS[key]
  if (t === undefined) throw new Error('story: no key ' + key)
  return storyFill(t, { ...(STORY_DRIVERS[driver] || STORY_DRIVERS['any']!), ...fields }, true)
}
"""


def page_ts() -> str:
    texts = {k: story.TEXTS[k] for k in story.PAGE}
    return (BANNER
            + "// The story's sentences the web app shows (#1355): story.PAGE's keys, the drivers' names and\n"
            + "// the fill. A plain script, as app.ts is: its names are the page's globals.\n"
            + f"const STORY_DRIVERS: Record<string, Record<string, string>> = {json.dumps(story.DRIVERS, indent=2)}\n"
            + f"const STORY_TEXTS: Record<string, string> = {json.dumps(texts, indent=2)}\n"
            + FILL_TS)


def host_ts() -> str:
    """mod/hooks/story.ts: story.HOST's keys filled for each host they are said for, one `as const`
    table per host, so a host reads its own sentence by key with its exact type."""
    out = [BANNER,
           "// The story's sentences the hosts say themselves (#1355): the Claude Code mod's refusals and\n",
           "// consent line (register.tsx), the OpenCode plugin's (chat.ts), and the skill blocks skill.ts\n",
           "// swaps for OpenCode's. Pure data: nothing runs at import.\n"]
    for driver, name in HOST_NAMES.items():
        table = {k: story.text(k, driver) for k in story.HOST if driver in story.ONLY.get(k, (driver,))}
        out.append(f"export const {name} = {json.dumps(table, indent=2, ensure_ascii=False)} as const\n")
    return "".join(out)


def filled_doc(body: str) -> str:
    """``body`` with each story block's text filled from story.py."""
    def one(m: re.Match) -> str:
        key, driver = m.group(2), m.group(3) or "any"
        return m.group(1) + story.text(key, driver) + "\n" + m.group(5)
    return BLOCK.sub(one, body)


def outputs() -> dict[Path, str]:
    out = {PAGE_TS: page_ts(), HOST_TS: host_ts()}
    for rel, blocks in story.DOCS.items():
        f = ROOT / rel
        body = f.read_text()
        found = [(m.group(2), m.group(3) or "any") for m in BLOCK.finditer(body)]
        if sorted(found) != sorted(blocks):
            raise SystemExit(f"gen_story: {rel} has the blocks {found}, story.DOCS says {list(blocks)}")
        out[f] = filled_doc(body)
    return out


def _rel(f: Path) -> str:
    return f.relative_to(ROOT).as_posix() if f.is_relative_to(ROOT) else str(f)


def check() -> list[str]:
    bad = []
    for f, want in outputs().items():
        rel = _rel(f)
        if not f.is_file():
            bad.append(f"{rel}: missing (python3 scripts/gen_story.py)")
        elif f.read_text() != want:
            bad.append(f"{rel}: not what workbench/story.py says (python3 scripts/gen_story.py, and commit it)")
    return bad


def main(argv: list[str]) -> int:
    if argv == ["--check"]:
        bad = check()
        if bad:
            print("\n".join(bad), file=sys.stderr)
            return 1
        print("story: every copy is what workbench/story.py says")
        return 0
    if argv:
        print(__doc__.strip(), file=sys.stderr)
        return 64
    wrote = []
    for f, want in outputs().items():
        if not f.is_file() or f.read_text() != want:
            f.write_text(want)
            wrote.append(_rel(f))
    print("story: wrote " + ", ".join(wrote) if wrote else "story: current")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
